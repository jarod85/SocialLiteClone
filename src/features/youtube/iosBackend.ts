/**
 * The YouTube backend on iOS: Lite Social's own TypeScript engine (innertube/) for
 * everything YouTube serves, and the iOS side of modules/youtube for what needs the
 * device. It has the same shape as the Android module, so screens don't care which runs.
 */
import type { VideoPlayer } from 'expo-video';

import { downloadStreams, engine } from './innertube';
import { networkError } from './innertube/errors';
import type { DownloadFormat, DownloadUpdate } from './types';

/** The Swift module (modules/youtube/ios). */
export interface IosYouTubeModule {
  /** Caps the height AVPlayer picks from the HLS manifest; null lets it pick freely. */
  capVideoHeight(player: VideoPlayer, height: number | null): Promise<void>;
  /** Downloads and joins the streams (modules/youtube/ios/Downloads.swift); progress comes as onDownloadUpdate. */
  startDownload(options: IosDownload): void;
  cancelDownload(id: string): void;
  getDownloads(): DownloadUpdate[];
  clearFinishedDownloads(): void;
  /** Pinch to zoom on a VideoView (its view tag), as on Android; the level comes as onZoomChange. */
  attachZoom(viewTag: number): Promise<boolean>;
  resetZoom(): Promise<void>;
  addListener(event: string, listener: (event: any) => void): { remove(): void };
  emit(event: string, payload: unknown): void;
}

/** What the Swift side downloads. `format` is the app's choice: 'mp3' means audio, saved as M4A. */
export interface IosDownload {
  id: string;
  title: string;
  format: DownloadFormat;
  videoUrl?: string;
  audioUrl: string;
  captionsUrl?: string;
  /** YouTube's length of the streams (see DownloadStreams.durationMs). */
  durationMs?: number;
  artist?: string;
  artworkUrl?: string;
}

interface DownloadOptions {
  url: string;
  title: string;
  format: DownloadFormat;
  maxHeight: number;
  captionLanguage?: string;
  captionAutoGenerated?: boolean;
}

const unsupported = (what: string) => () => {
  throw new Error(`${what} isn't available on iPhone.`);
};

export function createIosBackend(native: IosYouTubeModule) {
  return {
    ...engine,
    /** Finds the streams here (the engine), then the Swift side downloads them; failures before that are reported here. */
    startDownload(options: DownloadOptions): string {
      const id = `${Date.now().toString(36)}-${Math.random().toString(36).slice(2, 8)}`;
      const update = (u: Partial<DownloadUpdate>) =>
        native.emit('onDownloadUpdate', { id, title: options.title, format: options.format, state: 'queued', progress: 0, ...u });
      update({});
      void (async () => {
        try {
          const videoId = engine.parseVideoId(options.url);
          if (!videoId) throw new Error("This isn't a YouTube video link.");
          const streams = await downloadStreams(videoId, options.maxHeight);
          const video = options.format === 'mp4';
          const captionsUrl =
            video && options.captionLanguage
              ? (await engine.video(videoId)).captions.find(
                  (c) => c.language === options.captionLanguage && c.autoGenerated === !!options.captionAutoGenerated,
                )?.url
              : undefined;
          native.startDownload({
            id,
            title: options.title,
            format: options.format,
            videoUrl: video ? streams.video.url : undefined,
            audioUrl: streams.audio.url,
            captionsUrl,
            durationMs: streams.durationMs ?? undefined,
            artist: streams.author ?? undefined,
            artworkUrl: streams.thumbnail ?? undefined,
          });
        } catch (e) {
          update({ state: 'failed', error: networkError(e).message });
        }
      })();
      return id;
    },
    cancelDownload: (id: string) => native.cancelDownload(id),
    getDownloads: () => native.getDownloads(),
    clearFinishedDownloads: () => native.clearFinishedDownloads(),
    // Musicolet folders are Android-only: iOS saves audio to the Files app.
    pickMusicFolder: async () => null,
    hasMusicFolderAccess: (_tree: string) => false,
    listFolders: unsupported('Choosing a music folder') as () => Promise<string[]>,
    createFolder: unsupported('Choosing a music folder') as () => Promise<string>,
    describeFolder: (_tree: string, _path: string[]) => '',
    isMusicoletInstalled: () => false,
    // Full screen turns the app with expo-screen-orientation on iOS (fullscreen.ts).
    setFullscreen: async (_enabled: boolean) => undefined,
    attachZoom: (viewTag: number) => native.attachZoom(viewTag),
    resetZoom: () => native.resetZoom(),
    addListener: (event: string, listener: (event: any) => void) => native.addListener(event, listener),
  };
}
