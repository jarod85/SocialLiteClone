package com.jarod85.litesocial.youtube

import org.schabi.newpipe.extractor.MediaFormat
import org.schabi.newpipe.extractor.stream.StreamInfo
import org.schabi.newpipe.extractor.stream.SubtitlesStream
import java.io.IOException
import java.net.HttpURLConnection
import java.net.URL
import java.util.Locale

/**
 * Captions for downloaded videos: fetched from YouTube, turned into plain
 * timed lines, then written into the MP4 (Mp4Text) and as an .srt next to it.
 *
 * The parsing is pure Kotlin (no Android classes), so it's unit-tested on the JVM.
 */
object Captions {
  /** One caption on screen from [startMs] to [endMs]. */
  data class Cue(val startMs: Long, val endMs: Long, val text: String)

  /**
   * Formats tried in order. YouTube's "srv1" transcript has one entry per line
   * even for automatic captions, whose WebVTT version repeats every line
   * while it scrolls ("rolling" captions). TTML is often the only one NewPipe lists.
   */
  private val FORMATS = listOf(MediaFormat.TRANSCRIPT1, MediaFormat.TTML, MediaFormat.VTT)

  /** The video's captions in [language] (uploaded or automatic, as picked), or null if it has none. */
  fun find(info: StreamInfo, language: String, autoGenerated: Boolean): SubtitlesStream? {
    val tracks = info.subtitles.filter { it.isUrl && it.format in FORMATS }
    val same = tracks.filter { it.languageTag.equals(language, ignoreCase = true) }
    val candidates = same.filter { it.isAutoGenerated == autoGenerated }.ifEmpty { same }
    return candidates.minByOrNull { FORMATS.indexOf(it.format) }
  }

  fun download(track: SubtitlesStream): List<Cue> {
    val body = fetch(track.content)
    val cues = when (track.format) {
      MediaFormat.TRANSCRIPT1 -> parseTranscript(body)
      MediaFormat.TTML -> parseTtml(body)
      else -> parseVtt(body, rolling = track.isAutoGenerated)
    }
    if (cues.isEmpty()) throw IOException("The captions were empty")
    return cues
  }

  private fun fetch(url: String): String {
    val connection = URL(url).openConnection() as HttpURLConnection
    try {
      connection.connectTimeout = 15_000
      connection.readTimeout = 30_000
      connection.setRequestProperty("User-Agent", Extractor.BROWSER_USER_AGENT)
      val code = connection.responseCode
      if (code != 200) throw IOException("YouTube refused the captions (HTTP $code)")
      return connection.inputStream.use { it.readBytes().toString(Charsets.UTF_8) }
    } finally {
      connection.disconnect()
    }
  }

  // ------------------------------------------------------------------ parsing

  private val TRANSCRIPT_TEXT = Regex("""<text\b([^>]*)>(.*?)</text>""", RegexOption.DOT_MATCHES_ALL)
  private val ATTRIBUTE = Regex("""(\w+)="([^"]*)"""")

  /** YouTube's srv1 transcript: `<text start="1.2" dur="3.4">Hello</text>`, escaped once more inside. */
  fun parseTranscript(xml: String): List<Cue> {
    val cues = mutableListOf<Cue>()
    for (match in TRANSCRIPT_TEXT.findAll(xml)) {
      val attributes = ATTRIBUTE.findAll(match.groupValues[1]).associate { it.groupValues[1] to it.groupValues[2] }
      val start = attributes["start"]?.toDoubleOrNull() ?: continue
      val duration = attributes["dur"]?.toDoubleOrNull() ?: 2.0
      val text = cleanText(unescape(unescape(match.groupValues[2])))
      if (text.isEmpty()) continue
      cues += Cue(Math.round(start * 1000), Math.round((start + duration) * 1000), text)
    }
    return flatten(cues)
  }

  private val TTML_P = Regex("""<p(\s[^>]*)?>(.*?)</p>""", RegexOption.DOT_MATCHES_ALL)
  private val BR = Regex("""<br\s*/?>""", RegexOption.IGNORE_CASE)
  private val NEWLINES = Regex("""\s*[\r\n]+\s*""")

  /** TTML, as YouTube sends it: `<p begin="00:00:01.200" end="00:00:04.000">line<br/>line</p>`. */
  fun parseTtml(xml: String): List<Cue> {
    val cues = mutableListOf<Cue>()
    for (match in TTML_P.findAll(xml)) {
      val attributes = ATTRIBUTE.findAll(match.groupValues[1]).associate { it.groupValues[1] to it.groupValues[2] }
      val start = attributes["begin"]?.let(::ttmlTime) ?: continue
      val end = attributes["end"]?.let(::ttmlTime) ?: attributes["dur"]?.let(::ttmlTime)?.let { start + it } ?: continue
      // Line breaks in the file are layout; <br/> is a line break on screen.
      val text = cleanText(unescape(match.groupValues[2].replace(NEWLINES, " ").replace(BR, "\n")))
      if (text.isNotEmpty()) cues += Cue(start, end, text)
    }
    return flatten(cues)
  }

  private val TTML_CLOCK = Regex("""^(\d+):(\d{2}):(\d{2})(?:[.,](\d+))?$""")
  private val TTML_OFFSET = Regex("""^([\d.]+)(h|m|s|ms)$""")

  /** "00:01:02.500" or an offset ("62.5s", "1500ms"), in milliseconds; null if neither. */
  private fun ttmlTime(text: String): Long? {
    TTML_CLOCK.find(text.trim())?.let { m ->
      val (h, min, sec, frac) = m.destructured
      val millis = frac.padEnd(3, '0').take(3).toLongOrNull() ?: 0
      return ((h.toLong() * 60 + min.toLong()) * 60 + sec.toLong()) * 1000 + millis
    }
    val m = TTML_OFFSET.find(text.trim()) ?: return null
    val value = m.groupValues[1].toDoubleOrNull() ?: return null
    val factor = when (m.groupValues[2]) { "h" -> 3_600_000.0; "m" -> 60_000.0; "s" -> 1000.0; else -> 1.0 }
    return Math.round(value * factor)
  }

  private val VTT_TIMING = Regex("""^((?:\d+:)?\d{1,2}:\d{2}[.,]\d{3})\s+-->\s+((?:\d+:)?\d{1,2}:\d{2}[.,]\d{3})""")

  /**
   * WebVTT. Automatic captions scroll ([rolling]): each cue shows the previous
   * line again above the new one, and tiny cues hold the screen in between.
   * There, lines already shown by the cue before are dropped, so each line
   * appears once.
   */
  fun parseVtt(vtt: String, rolling: Boolean = false): List<Cue> {
    val cues = mutableListOf<Cue>()
    val lines = vtt.replace("\r\n", "\n").replace('\r', '\n').split('\n')
    var i = 0
    var previousLines = emptyList<String>()
    while (i < lines.size) {
      val timing = VTT_TIMING.find(lines[i].trim())
      if (timing == null) {
        i++
        continue
      }
      val start = vttTime(timing.groupValues[1])
      val end = vttTime(timing.groupValues[2])
      i++
      val text = mutableListOf<String>()
      // A cue ends at an empty line; automatic captions start theirs with a line holding one space.
      while (i < lines.size && lines[i].isNotEmpty()) {
        text += cleanText(unescape(lines[i]))
        i++
      }
      val cueLines = text.filter { it.isNotEmpty() }
      val fresh = if (rolling) cueLines.filter { it !in previousLines } else cueLines
      if (cueLines.isNotEmpty()) previousLines = cueLines
      if (fresh.isEmpty() || end <= start) continue
      cues += Cue(start, end, fresh.joinToString("\n"))
    }
    return flatten(cues)
  }

  private fun vttTime(text: String): Long {
    val parts = text.replace(',', '.').split(':')
    val (seconds, millis) = parts.last().split('.')
    val minutes = parts[parts.size - 2].toLong()
    val hours = if (parts.size == 3) parts[0].toLong() else 0L
    return ((hours * 60 + minutes) * 60 + seconds.toLong()) * 1000 + millis.toLong()
  }

  /**
   * Sorted, without overlaps: a cue ends where the next one starts (automatic
   * captions often say a line lasts past the next one), and a line repeated
   * right after itself is merged into one.
   */
  fun flatten(cues: List<Cue>): List<Cue> {
    val sorted = cues.filter { it.endMs > it.startMs && it.text.isNotBlank() }.sortedBy { it.startMs }
    val out = mutableListOf<Cue>()
    for ((index, cue) in sorted.withIndex()) {
      val next = sorted.getOrNull(index + 1)
      val end = if (next != null && next.startMs < cue.endMs) next.startMs else cue.endMs
      if (end <= cue.startMs) continue
      val last = out.lastOrNull()
      if (last != null && last.text == cue.text && cue.startMs - last.endMs <= 50) {
        out[out.size - 1] = last.copy(endMs = end)
      } else {
        out += cue.copy(endMs = end)
      }
    }
    return out
  }

  private val TAG = Regex("""<[^>]*>""")
  private val SPACES = Regex("""[ \t ]+""")

  /** Without markup (<c>, <i>, word timings), extra spaces or empty lines. */
  private fun cleanText(text: String): String =
    text.replace(TAG, "")
      .split('\n')
      .map { it.replace(SPACES, " ").trim() }
      .filter { it.isNotEmpty() }
      .joinToString("\n")

  private val ENTITY = Regex("""&(#x[0-9a-fA-F]+|#\d+|amp|lt|gt|quot|apos|nbsp);""")

  private fun unescape(text: String): String =
    ENTITY.replace(text) { m ->
      when (val name = m.groupValues[1]) {
        "amp" -> "&"
        "lt" -> "<"
        "gt" -> ">"
        "quot" -> "\""
        "apos" -> "'"
        "nbsp" -> " "
        else -> {
          val code = if (name.startsWith("#x")) name.substring(2).toIntOrNull(16) else name.substring(1).toIntOrNull()
          code?.takeIf { Character.isValidCodePoint(it) }?.let { String(Character.toChars(it)) } ?: m.value
        }
      }
    }

  // ------------------------------------------------------------------ output

  /** SubRip, the format video players read from a file next to the video. */
  fun toSrt(cues: List<Cue>): String {
    val sb = StringBuilder()
    cues.forEachIndexed { index, cue ->
      sb.append(index + 1).append("\r\n")
      sb.append(srtTime(cue.startMs)).append(" --> ").append(srtTime(cue.endMs)).append("\r\n")
      sb.append(cue.text.replace("\n", "\r\n")).append("\r\n\r\n")
    }
    return sb.toString()
  }

  private fun srtTime(ms: Long): String =
    String.format(Locale.US, "%02d:%02d:%02d,%03d", ms / 3_600_000, ms / 60_000 % 60, ms / 1000 % 60, ms % 1000)

  /** ISO 639-2/T code for an MP4 track ("en" is "eng", "zh-CN" is "zho"); "und" if unknown. */
  fun iso3Language(tag: String): String =
    runCatching { Locale.forLanguageTag(tag).isO3Language }.getOrNull()?.takeIf { it.length == 3 } ?: "und"
}
