/**
 * The YouTube backend. Android: the native module (modules/youtube, NewPipe Extractor).
 * iOS: Lite Social's own engine plus the module's iOS side (iosBackend.ts). This is the
 * only file that picks by OS; screens read `youtubeFeatures` for what differs.
 * Missing in Expo Go: `youtubeAvailable` is then false and calls throw.
 */
import { requireOptionalNativeModule } from 'expo';
import type { VideoPlayer } from 'expo-video';
import { Platform } from 'react-native';

import { createIosBackend, type IosYouTubeModule } from './iosBackend';

import type { ChannelPage, DownloadFormat, DownloadUpdate, FeedResult, MusicFolder, Page, SearchItem, SwipeLevel, Video, VideoDetails } from './types';

interface YouTubeNativeModule {
  search(query: string, kind: 'all' | 'videos' | 'channels'): Promise<Page<SearchItem>>;
  more(token: string): Promise<Page<SearchItem>>;
  channel(idOrUrl: string): Promise<ChannelPage>;
  feed(channelIds: string[]): Promise<FeedResult>;
  video(url: string): Promise<VideoDetails>;
  parseVideoId(url: string): string | null;
  startDownload(options: {
    url: string;
    title: string;
    format: DownloadFormat;
    maxHeight: number;
    mp3Kbps: number;
    folderTree?: string;
    folderPath?: string[];
    /** MP4 only: captions to add (the language tag of one of the video's caption tracks). */
    captionLanguage?: string;
    captionAutoGenerated?: boolean;
  }): string;
  cancelDownload(id: string): void;
  getDownloads(): DownloadUpdate[];
  clearFinishedDownloads(): void;
  pickMusicFolder(): Promise<MusicFolder | null>;
  hasMusicFolderAccess(tree: string): boolean;
  listFolders(tree: string, path: string[]): Promise<string[]>;
  /** Resolves to the folder name as stored (unsupported characters replaced). */
  createFolder(tree: string, path: string[], name: string): Promise<string>;
  describeFolder(tree: string, path: string[]): string;
  isMusicoletInstalled(): boolean;
  /** Sideways without the system bars, or back to normal. */
  setFullscreen(enabled: boolean): Promise<void>;
  /** Pinch to zoom on the video of an expo-video VideoView (its view tag; needs surfaceType="textureView"). */
  attachZoom(viewTag: number): Promise<boolean>;
  resetZoom(): Promise<void>;
  addListener(event: 'onDownloadUpdate', listener: (update: DownloadUpdate) => void): { remove(): void };
  /** The phone was turned upright while in full screen (with auto-rotate on). */
  addListener(event: 'onFullscreenExitRequest', listener: () => void): { remove(): void };
  addListener(event: 'onZoomChange', listener: (event: { scale: number }) => void): { remove(): void };
  /** A swipe in full screen set the brightness (left half) or the media volume (right half), 0–1. */
  addListener(event: 'onSwipeAdjust', listener: (event: SwipeLevel) => void): { remove(): void };
}

const iosNative = Platform.OS === 'ios' ? requireOptionalNativeModule<IosYouTubeModule>('LiteSocialYouTube') : null;

const module: YouTubeNativeModule | null =
  Platform.OS === 'android'
    ? requireOptionalNativeModule<YouTubeNativeModule>('LiteSocialYouTube')
    : iosNative
      ? (createIosBackend(iosNative) as unknown as YouTubeNativeModule)
      : null;

export const youtubeAvailable = module !== null;

export function youtube(): YouTubeNativeModule {
  if (!module) throw new Error('YouTube needs the Lite Social app (it is not available in Expo Go).');
  return module;
}

/** What the YouTube backend on this phone can do, where Android and iOS differ. */
export interface YouTubeFeatures {
  /** Audio downloads: MP3 into a Musicolet folder (Android) or M4A into the Files app (iOS, which has no MP3 encoder). */
  audioFormat: 'mp3' | 'm4a';
  /** A music folder to pick, with subfolders per song (Android). */
  musicFolder: boolean;
  /** Downloads finish with the app closed (Android's foreground service); iOS needs the app open. */
  backgroundDownloads: boolean;
  /** Full screen turns the app sideways natively, with the phone's rotation handled there (Android); else via expo-screen-orientation (iOS). */
  nativeFullscreen: boolean;
  /** Full-screen swipes set brightness and volume (Android). */
  swipeAdjust: boolean;
  /** Pinch to zoom on the player (Android VideoZoom.kt, iOS VideoZoom.swift); the app shows the level and a reset. */
  nativeZoom: boolean;
  /** Captions shown by the player from its DASH manifest (Android), or drawn by the app over the video (iOS, HLS). */
  captions: 'player' | 'overlay';
  /** iOS: caps the height the player picks from the HLS manifest, for a picked quality. */
  capVideoHeight?: (player: VideoPlayer, height: number | null) => void;
}

export const youtubeFeatures: YouTubeFeatures =
  Platform.OS === 'ios'
    ? {
        audioFormat: 'm4a',
        musicFolder: false,
        backgroundDownloads: false,
        nativeFullscreen: false,
        swipeAdjust: false,
        nativeZoom: true,
        captions: 'overlay',
        capVideoHeight: iosNative ? (player, height) => void iosNative.capVideoHeight(player, height).catch(() => undefined) : undefined,
      }
    : {
        audioFormat: 'mp3',
        musicFolder: true,
        backgroundDownloads: true,
        nativeFullscreen: true,
        swipeAdjust: true,
        nativeZoom: true,
        captions: 'player',
      };

/**
 * The readable part of an error from the native module. Expo puts "Call to function
 * 'LiteSocialYouTube.video' has been rejected." and "→ Caused by: " in front of the module's
 * own message (modules/youtube Errors.kt); only that message is kept.
 */
export function errorText(e: unknown): string {
  const message = e instanceof Error ? e.message : String(e);
  const marker = '→ Caused by: ';
  const at = message.lastIndexOf(marker);
  return at === -1 ? message : message.slice(at + marker.length).trim();
}

export const watchUrl = (id: string) => `https://www.youtube.com/watch?v=${id}`;

export function videoPage(items: SearchItem[]): Video[] {
  return items.filter((i): i is Video => i.type === 'video');
}
