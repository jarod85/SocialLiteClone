/**
 * A video's details and streams on iOS, from the visionOS player (as NewPipe does on
 * Android). iOS plays YouTube's HLS manifest natively (AVPlayer), so there is no local
 * DASH manifest: one HLS source, and qualities that cap the player's height.
 */
import { parseYouTubeLink } from '../links';
import type { CaptionTrack, DescriptionLink, VideoDetails, VideoQuality } from '../types';
import { playabilityError, YouTubeError } from './errors';
import { hlsFrameRate, hlsHeights } from './hls';
import { bestImage, text, watchUrl } from './parse';
import { innertube, resetVisitorData } from './request';

function videoId(input: string): string {
  if (/^[\w-]{11}$/.test(input)) return input;
  const link = parseYouTubeLink(input);
  if (link?.kind === 'video' || link?.kind === 'short') return link.id;
  throw new YouTubeError('ERR_YOUTUBE', "This isn't a YouTube video link.");
}

/** The visionOS player answer for a video, or the reason it can't play. */
async function playerResponse(id: string): Promise<any> {
  const json = await innertube('visionos', 'player', { videoId: id });
  const error = playabilityError(json?.playabilityStatus);
  if (error) {
    // A blocked visitor id stays blocked: ask for a new one next time.
    if (error.code === 'ERR_YOUTUBE_BLOCKED') resetVisitorData();
    throw error;
  }
  return json;
}

/** The http(s) links in a description, as the watch screen shows them. */
export function descriptionLinks(description: string): DescriptionLink[] {
  const links: DescriptionLink[] = [];
  for (const m of description.matchAll(/https?:\/\/[^\s<>"]+/g)) {
    const url = m[0].replace(/[).,!?;:'"]+$/, '');
    links.push({ start: m.index!, end: m.index! + url.length, url });
  }
  return links;
}

function captions(json: any): CaptionTrack[] {
  const tracks: any[] = json?.captions?.playerCaptionsTracklistRenderer?.captionTracks ?? [];
  const all: CaptionTrack[] = tracks
    .filter((t) => typeof t?.baseUrl === 'string' && typeof t?.languageCode === 'string')
    .map((t, i) => ({
      id: `cc${i}`,
      language: t.languageCode,
      label: text(t.name) ?? t.languageCode,
      autoGenerated: t.kind === 'asr',
      url: `${t.baseUrl}&fmt=vtt`,
    }));
  return [...all.filter((c) => !c.autoGenerated), ...all.filter((c) => c.autoGenerated)];
}

function qualities(hls: string, master: string | null): VideoQuality[] {
  if (!master) return [];
  return hlsHeights(master).map((height) => {
    const fps = hlsFrameRate(master, height);
    return { height, label: fps > 30 ? `${height}p${fps}` : `${height}p`, uri: hls, contentType: 'hls' };
  });
}

/** Details from a visionOS player answer, with the HLS master playlist's text (null when unknown). */
export function parsePlayer(json: any, master: string | null): VideoDetails {
  const d = json?.videoDetails ?? {};
  const hls: string | undefined = json?.streamingData?.hlsManifestUrl;
  const isLive = d.isLive === true;
  const description: string = d.shortDescription ?? '';
  const views = Number(d.viewCount);
  const length = Number(d.lengthSeconds);
  return {
    id: d.videoId,
    url: watchUrl(d.videoId),
    title: d.title ?? '',
    channelName: d.author ?? null,
    channelId: d.channelId ?? null,
    channelAvatar: null,
    thumbnail: bestImage(d.thumbnail),
    description,
    descriptionLinks: descriptionLinks(description),
    durationSeconds: !isLive && length > 0 ? length : null,
    uploadedAt: null,
    viewCount: Number.isFinite(views) ? views : null,
    likeCount: null,
    isShort: false,
    isLive,
    sources: hls ? [{ uri: hls, contentType: 'hls' }] : [],
    qualities: hls && !isLive ? qualities(hls, master) : [],
    captions: captions(json),
  };
}

/** Optional extras: a failure here never stops the video from playing. */
async function optional<T>(work: () => Promise<T>): Promise<T | null> {
  try {
    return await work();
  } catch {
    return null;
  }
}

async function fetchText(url: string): Promise<string> {
  const response = await fetch(url);
  if (!response.ok) throw new Error(`HTTP ${response.status}`);
  return response.text();
}

export async function video(url: string): Promise<VideoDetails> {
  const id = videoId(url);
  const json = await playerResponse(id);
  const hls: string | undefined = json?.streamingData?.hlsManifestUrl;
  const live = json?.videoDetails?.isLive === true;
  const [master, web] = await Promise.all([
    hls && !live ? optional(() => fetchText(hls)) : null,
    // The upload date isn't in the visionOS answer; the website's player has it.
    optional(() => innertube('web', 'player', { videoId: id, contentCheckOk: true, racyCheckOk: true })),
  ]);
  const details = parsePlayer(json, master);
  const published = Date.parse(web?.microformat?.playerMicroformatRenderer?.publishDate ?? '');
  return Number.isFinite(published) ? { ...details, uploadedAt: published } : details;
}

/** The streams a download joins: H.264 video up to `maxHeight` (else the lowest there is) and AAC audio. */
export async function downloadStreams(id: string, maxHeight: number): Promise<{ video: { url: string; height: number }; audio: { url: string } }> {
  const formats: any[] = (await playerResponse(id))?.streamingData?.adaptiveFormats ?? [];
  const h264 = formats
    .filter((f) => typeof f.url === 'string' && /^video\/mp4; codecs="avc1/.test(f.mimeType ?? '') && f.height > 0)
    .sort((a, b) => b.height - a.height || (b.bitrate ?? 0) - (a.bitrate ?? 0));
  const video = h264.find((f) => f.height <= maxHeight) ?? h264[h264.length - 1];
  const aac = formats.filter((f) => typeof f.url === 'string' && /^audio\/mp4/.test(f.mimeType ?? ''));
  const audio = aac.find((f) => f.itag === 140) ?? aac.sort((a, b) => (b.bitrate ?? 0) - (a.bitrate ?? 0))[0];
  if (!video || !audio) throw new YouTubeError('ERR_YOUTUBE', 'No downloadable version of this video was found.');
  return { video: { url: video.url, height: video.height }, audio: { url: audio.url } };
}
