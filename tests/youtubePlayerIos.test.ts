/**
 * The shared YouTube player on iOS (jest-expo runs as iOS): HLS qualities cap the
 * player's height, and captions are drawn by the app instead of the player.
 */
import type { VideoDetails } from '@/features/youtube/types';

const mockCapVideoHeight = jest.fn();
jest.mock('expo', () => ({
  requireOptionalNativeModule: (name: string) =>
    name === 'LiteSocialYouTube' ? { capVideoHeight: async (...args: unknown[]) => mockCapVideoHeight(...args), addListener: jest.fn(() => ({ remove() {} })), emit: jest.fn() } : null,
}));

const mockSubtitleSet = jest.fn();
const mockPlayer: Record<string, unknown> = {
  replaceAsync: jest.fn(async () => undefined),
  play: jest.fn(),
  pause: jest.fn(),
  addListener: jest.fn(),
  availableSubtitleTracks: [],
  currentTime: 0,
  status: 'readyToPlay',
};
Object.defineProperty(mockPlayer, 'subtitleTrack', { get: () => null, set: mockSubtitleSet });
jest.mock('expo-video', () => ({ createVideoPlayer: () => mockPlayer }));

// eslint-disable-next-line import/first
import { play, setCaption, setQuality, stop, usePlayer } from '@/features/youtube/player';
// eslint-disable-next-line import/first
import { useYouTubeSettings } from '@/features/youtube/stores';

const HLS = 'https://manifest.googlevideo.com/api/manifest/hls_variant/id/test/file/index.m3u8';

const details = (id: string): VideoDetails => ({
  id,
  url: `https://www.youtube.com/watch?v=${id}`,
  title: 'A video',
  description: '',
  isShort: false,
  isLive: false,
  sources: [{ uri: HLS, contentType: 'hls' }],
  qualities: [720, 360].map((height) => ({ height, label: `${height}p`, uri: HLS, contentType: 'hls' as const })),
  captions: [{ id: 'cc0', language: 'en', label: 'English', autoGenerated: false, url: 'https://www.youtube.com/api/timedtext?v=x&fmt=vtt' }],
});

beforeEach(() => {
  stop();
  jest.clearAllMocks();
  useYouTubeSettings.getState().setPlaybackHeight(null);
});

it('plays the HLS manifest and caps the height to the quality picked', async () => {
  useYouTubeSettings.getState().setPlaybackHeight(720);
  await play(details('aaaaaaaaaaa'));
  expect(mockPlayer.replaceAsync).toHaveBeenLastCalledWith(expect.objectContaining({ uri: HLS, contentType: 'hls' }));
  expect(mockCapVideoHeight).toHaveBeenLastCalledWith(mockPlayer, 720);
  expect(usePlayer.getState().quality).toBe(720);

  await setQuality(null);
  expect(mockCapVideoHeight).toHaveBeenLastCalledWith(mockPlayer, null);
  expect(usePlayer.getState().quality).toBeNull();
});

it('offers captions and shows them without the player’s own subtitle track', async () => {
  await play(details('bbbbbbbbbbb'));
  expect(usePlayer.getState().captionsAvailable).toBe(true);
  setCaption('cc0');
  expect(usePlayer.getState().caption).toBe('cc0');
  setCaption(null);
  expect(usePlayer.getState().caption).toBeNull();
  expect(mockSubtitleSet).not.toHaveBeenCalledWith(expect.anything());
});
