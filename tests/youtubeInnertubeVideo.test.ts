/**
 * One video's details on iOS: playback from YouTube's HLS manifest, the
 * qualities it offers, captions, and the streams a download uses.
 */
import { hlsHeights } from '@/features/youtube/innertube/hls';
import { resetVisitorData } from '@/features/youtube/innertube/request';
import { descriptionLinks, downloadStreams, parsePlayer, video } from '@/features/youtube/innertube/video';

import { fixture, jsonFixture } from './fixtures';

const MASTER = fixture('youtube/master.m3u8');
const HLS = 'https://manifest.googlevideo.com/api/manifest/hls_variant/id/test/file/index.m3u8';
const player = () => jsonFixture<any>('youtube/player-visionos.json');

function answer(body: string, status = 200): Response {
  return { ok: status < 300, status, json: async () => JSON.parse(body), text: async () => body } as Response;
}

const fetchMock = jest.fn();
beforeEach(() => {
  fetchMock.mockReset();
  globalThis.fetch = fetchMock as unknown as typeof fetch;
  resetVisitorData();
});

describe('hlsHeights', () => {
  it('lists the H.264 heights the manifest offers, highest first, up to 1080', () => {
    expect(hlsHeights(MASTER)).toEqual([1080, 720, 480, 360, 240, 144]);
  });
});

describe('parsePlayer', () => {
  const details = parsePlayer(player(), MASTER);

  it('plays the HLS manifest and offers its qualities', () => {
    expect(details.sources).toEqual([{ uri: HLS, contentType: 'hls' }]);
    expect(details.qualities[0]).toEqual({ height: 1080, label: '1080p', uri: HLS, contentType: 'hls' });
    expect(details.qualities.map((q) => q.height)).toEqual([1080, 720, 480, 360, 240, 144]);
  });

  it('reads the details', () => {
    expect(details).toMatchObject({
      id: 'dQw4w9WgXcQ',
      url: 'https://www.youtube.com/watch?v=dQw4w9WgXcQ',
      title: 'Rick Astley - Never Gonna Give You Up (Official Video) (4K Remaster)',
      channelName: 'Rick Astley',
      channelId: 'UCuAXFkgsw1L7xaCfnd5JJOw',
      thumbnail: 'https://i.ytimg.com/vi/dQw4w9WgXcQ/hq720.jpg',
      durationSeconds: 213,
      viewCount: 1840977009,
      isShort: false,
      isLive: false,
    });
    expect(details.description).toContain('Never Gonna Give You Up');
  });

  it('lists captions, uploaded ones first, each with its WebVTT address', () => {
    expect(details.captions.map((c) => [c.id, c.language, c.label, c.autoGenerated])).toEqual([
      ['cc0', 'en', 'English', false],
      ['cc2', 'de-DE', 'German (Germany)', false],
      ['cc1', 'en', 'English (auto-generated)', true],
    ]);
    for (const c of details.captions) expect(c.url).toMatch(/^https:\/\/www\.youtube\.com\/api\/timedtext\?.*&fmt=vtt$/);
  });

  it('offers no qualities for a live stream', () => {
    const live = player();
    live.videoDetails.isLive = true;
    const d = parsePlayer(live, null);
    expect(d.isLive).toBe(true);
    expect(d.qualities).toEqual([]);
    expect(d.sources).toEqual([{ uri: HLS, contentType: 'hls' }]);
  });
});

describe('descriptionLinks', () => {
  it('finds the links in a description', () => {
    const text = 'Get it here: https://linktr.ee/rickastleynever.\nMore (https://example.com/a?b=1)';
    expect(descriptionLinks(text)).toEqual([
      { start: 13, end: 46, url: 'https://linktr.ee/rickastleynever' },
      { start: 54, end: 79, url: 'https://example.com/a?b=1' },
    ]);
  });
});

describe('video', () => {
  it('asks for the streams, the manifest and the upload date', async () => {
    fetchMock.mockImplementation(async (url: string) => {
      if (url.includes('/visitor_id')) return answer(JSON.stringify({ responseContext: { visitorData: 'V' } }));
      if (url.startsWith('https://youtubei.googleapis.com/')) return answer(fixture('youtube/player-visionos.json'));
      if (url === HLS) return answer(MASTER);
      if (url.includes('www.youtube.com/youtubei/v1/player')) {
        return answer(JSON.stringify({ microformat: { playerMicroformatRenderer: { publishDate: '2009-10-24T23:57:33-07:00' } } }));
      }
      throw new Error(`unexpected ${url}`);
    });
    const d = await video('https://youtu.be/dQw4w9WgXcQ');
    expect(d.qualities).toHaveLength(6);
    expect(d.uploadedAt).toBe(Date.parse('2009-10-24T23:57:33-07:00'));
  });

  it('still plays when the date or the manifest list cannot be read', async () => {
    fetchMock.mockImplementation(async (url: string) => {
      if (url.includes('/visitor_id')) return answer(JSON.stringify({ responseContext: { visitorData: 'V' } }));
      if (url.startsWith('https://youtubei.googleapis.com/')) return answer(fixture('youtube/player-visionos.json'));
      throw new TypeError('Network request failed');
    });
    const d = await video('dQw4w9WgXcQ');
    expect(d.sources).toHaveLength(1);
    expect(d.qualities).toEqual([]);
    expect(d.uploadedAt ?? null).toBeNull();
  });

  it('reports a bot check as a blocked network', async () => {
    fetchMock.mockImplementation(async (url: string) =>
      url.includes('/visitor_id') ? answer(JSON.stringify({ responseContext: { visitorData: 'V' } })) : answer(fixture('youtube/player-blocked.json')),
    );
    await expect(video('https://www.youtube.com/watch?v=dQw4w9WgXcQ')).rejects.toMatchObject({ code: 'ERR_YOUTUBE_BLOCKED' });
  });

  it('rejects something that is not a video link', async () => {
    await expect(video('https://www.youtube.com/@veritasium')).rejects.toThrow("This isn't a YouTube video link.");
  });
});

describe('downloadStreams', () => {
  it('picks the best H.264 video up to the height asked for, and AAC audio', async () => {
    fetchMock.mockImplementation(async (url: string) =>
      url.includes('/visitor_id') ? answer(JSON.stringify({ responseContext: { visitorData: 'V' } })) : answer(fixture('youtube/player-visionos.json')),
    );
    const s = await downloadStreams('dQw4w9WgXcQ', 720);
    expect(s.video).toEqual({ url: 'https://rr1---sn-test.googlevideo.com/videoplayback?itag=135&id=test', height: 480 });
    expect(s.audio).toEqual({ url: 'https://rr1---sn-test.googlevideo.com/videoplayback?itag=140&id=test' });
    expect((await downloadStreams('dQw4w9WgXcQ', 144)).video.height).toBe(360);
  });
});
